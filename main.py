import pandas as pd
from datasets import load_dataset

# 1. Download the raw dataset from Hugging Face
raw_data = load_dataset("bitext/Bitext-customer-support-llm-chatbot-training-dataset")

# 2. Convert it into a Pandas DataFrame (think of this as a code-based Excel sheet)
df = pd.DataFrame(raw_data['train'])

# 3. Data Cleaning: Drop rows with missing data and remove duplicate queries
df.dropna(subset=['instruction', 'response'], inplace=True)
df.drop_duplicates(subset=['instruction'], inplace=True)

# 4. Feature Selection: Keep only the columns we actually need for the AI
df = df[['category', 'instruction', 'response']]

# 5. Rename columns so they align with our business logic
df.columns = ['ticket_category', 'customer_query', 'historical_resolution']

# Display the first 5 rows to verify the cleaning worked
print(df.head())

