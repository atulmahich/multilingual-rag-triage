from sentence_transformers import SentenceTransformer
import numpy as np

# 1. Load the Multilingual Embedding Model
# This specific model understands over 50 languages and aligns them in the same semantic space
print("Downloading the multilingual embedding model (this may take a minute)...")
model = SentenceTransformer('paraphrase-multilingual-MiniLM-L12-v2')

# 2. Extract a sample of our cleaned resolutions
# We use 100 rows to quickly test the pipeline
sample_resolutions = df['historical_resolution'].head(100).tolist()

# 3. Convert the text into vectors
print("Generating embeddings for the resolutions...")
resolution_embeddings = model.encode(sample_resolutions)

# 4. Verify the output
print(f"\nSuccessfully created {len(resolution_embeddings)} vector embeddings.")
print(f"Each vector is an array of {len(resolution_embeddings[0])} numbers.")
print("Here are the first 5 numbers of the first vector:")
print(resolution_embeddings[0][:5])

from sentence_transformers import util

# 1. Simulate an incoming customer ticket in German
# Meaning: "How do I create a new account?"
customer_query = "Wie erstelle ich ein neues Konto?"
print(f"Incoming Customer Query (German): '{customer_query}'\n")

# 2. Embed the query using the exact same model
query_embedding = model.encode(customer_query)

# 3. Perform the Semantic Search
# This calculates the cosine similarity between the query vector and all 100 stored resolution vectors
# top_k=1 tells the system to only return the single best match
hits = util.semantic_search(query_embedding, resolution_embeddings, top_k=1)

# 4. Extract the results
best_match_index = hits[0][0]['corpus_id']
similarity_score = hits[0][0]['score']

# 5. Display the matching document from our original Pandas DataFrame
print(f"Similarity Score: {similarity_score:.2f} (1.0 is a perfect semantic match)\n")
print("--- Retrieved Internal Resolution Document (English) ---")
print(df['historical_resolution'].iloc[best_match_index])

